#!/usr/bin/env bash
# Generate packs/index.yaml — a machine-readable catalog of every pack in this
# registry, so a consumer (codeoid) can list what's available cheaply (one file
# over raw-git) without cloning + walking the whole tree.
#
# A pack is packs/<id>/pack.yaml (schema: codeoid/pack@v1). This scans them and
# emits id / name / version / path / description per pack. Run from the repo root
# (or anywhere — it resolves its own location) and commit the result.
#
# Dependency-free (bash + awk), matching the rest of bin/.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
packs_dir="$repo_root/packs"
out="$packs_dir/index.yaml"

if [[ ! -d "$packs_dir" ]]; then
  echo "no packs/ directory at $packs_dir" >&2
  exit 1
fi

# Extract one scalar / folded field from a pack.yaml. For a folded/inline
# `description`, collapse its continuation lines into a single trimmed string.
field() {
  local file="$1" key="$2"
  awk -v key="$key" '
    # Top-level "key: value"
    $0 ~ "^" key ":" {
      line = $0
      sub("^" key ":[[:space:]]*", "", line)
      # Folded/literal block scalar — collect the following indented lines.
      if (line == ">" || line == "|" || line == ">-" || line == "|-" || line == "") {
        block = ""
        while ((getline nxt) > 0) {
          if (nxt ~ /^[[:space:]]/) {
            gsub(/^[[:space:]]+/, "", nxt)
            block = (block == "" ? nxt : block " " nxt)
          } else if (nxt ~ /^[[:space:]]*$/) {
            continue
          } else {
            break
          }
        }
        print block
      } else {
        # Strip surrounding quotes on an inline value.
        gsub(/^"|"$/, "", line)
        print line
      }
      exit
    }
  ' "$file"
}

# YAML-escape a value for a double-quoted scalar.
esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT  # don't leave a temp file behind on error/interrupt
{
  echo "# Generated by bin/gen-pack-index.sh — do not edit by hand."
  echo "schema: codeoid/pack-index@v1"
  echo "packs:"
} >"$tmp"

count=0
for dir in "$packs_dir"/*/; do
  manifest="$dir/pack.yaml"
  [[ -f "$manifest" ]] || continue
  schema="$(field "$manifest" schema)"
  [[ "$schema" == "codeoid/pack@v1" ]] || continue
  id="$(field "$manifest" id)"
  name="$(field "$manifest" name)"
  version="$(field "$manifest" version)"
  desc="$(field "$manifest" description)"
  dir_trimmed="${dir%/}"        # pure-bash basename — no subprocess per pack
  rel="packs/${dir_trimmed##*/}"
  [[ -n "$id" && -n "$name" && -n "$version" ]] || {
    echo "warning: skipping $rel (missing id/name/version)" >&2
    continue
  }
  {
    echo "  - id: \"$(esc "$id")\""
    echo "    name: \"$(esc "$name")\""
    echo "    version: \"$(esc "$version")\""
    echo "    path: \"$(esc "$rel")\""
    [[ -n "$desc" ]] && echo "    description: \"$(esc "$desc")\""
  } >>"$tmp"
  count=$((count + 1))
done

mv "$tmp" "$out"
echo "wrote $out ($count pack(s))"
